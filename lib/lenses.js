const ORDER = ['concept', 'trace', 'adversarial', 'boundary', 'textbook'];

/* 默认分配：让开箱即用的质检员A/B 拿到不同视角，而不是同一个视角各跑一遍 */
function defaultLensFor(role) {
  if (!role) return 'concept';
  const m = /^verifier(\d+)$/.exec(role);
  if (m) return ORDER[(+m[1] - 1) % ORDER.length];
  return 'concept';
}

/* 取视角定义；未配置/配错 → 回退到该岗位的默认视角（保证永远有视角，不会退化成"无提示"） */
function get(id, role) {
  if (id && LENSES[id]) return LENSES[id];
  return LENSES[defaultLensFor(role)];
}

/* 供前端渲染选择器 */
function list() {
  return ORDER.map(k => ({ id: k, label: LENSES[k].label, desc: LENSES[k].desc, temp: LENSES[k].temp }));
}

function isLens(id) { return !!(id && LENSES[id]); }

module.exports = { LENSES, ORDER, list, get, isLens, defaultLensFor };
