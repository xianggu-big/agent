/* 质检视角（Lens）：让"同一个模型"也能从不同侧重点审题
 *
 * 为什么需要：
 *   如果两个质检员拿到的是同一份提示词，哪怕是两个不同模型，它们也会走同一条推理路径 ——
 *   看到同一个坑、跳过同一个坑，分歧信号很弱。真正有价值的交叉质检 = 异构模型 × 异构视角。
 *
 *   视角不是"假装人设"，而是【换一条解题路径】：
 *     概念派 走定义/定理 → 违反定义即错
 *     演算派 走逐步模拟     → 数值算不出即错
 *     反证派 走构造反例     → 能推翻的选项不要
 *     边界派 走退化场景     → 空表/单元素/满栈/溢出
 *     教材派 走标准结论     → 与教材原话不一致即存疑
 *   同一个模型在不同路径上犯的错不一样，因此分歧能真实暴露"这题不稳"。
 *
 * 诚实说明（已写进界面文案）：
 *   同模型 + 换视角 = 去相关（decorrelated），能减少"共同盲区"，但不能消除模型自身的系统性偏差。
 *   最强配置是：不同供应商 + 不同视角。同供应商 + 不同视角是次优选，胜于"同供应商 + 同视角"。
 */
